def patch_step0_fold_text_embedding(core, folds_k, fold2emb: Dict[int, np.ndarray]):
    orig_fit, orig_transform = getattr(core, "fit_text_embedder", None), getattr(core, "transform_text_embedder", None)
    K = len(folds_k)
    state = {"call_count": 0, "fid": 0, "train_len": None, "test_len": None, "emb_tr": None, "emb_te": None}

    def fit_text_embedder_patched(train_text, dim=50, min_df=2, **kwargs):
        state["call_count"] += 1
        fid = ((state["call_count"] - 1) % K) + 1
        state["fid"] = fid
        if fid in fold2emb:
            tr, te = np.array(folds_k[fid - 1]["train_idx"], dtype=int), np.array(folds_k[fid - 1]["test_idx"],
                                                                                  dtype=int)
            emb_all = np.asarray(fold2emb[fid], dtype=float)
            state["train_len"], state["test_len"] = int(len(tr)), int(len(te))
            state["emb_tr"], state["emb_te"] = emb_all[tr, :int(dim)], emb_all[te, :int(dim)]
            return "__CACHED__", "__CACHED__"
        return orig_fit(train_text, dim=dim, min_df=min_df)

    def transform_text_embedder_patched(tfidf, svd, texts, **kwargs):
        if tfidf == "__CACHED__" and svd == "__CACHED__":
            if state.get("train_len") is not None and len(texts) == state["train_len"]: return np.asarray(
                state["emb_tr"], dtype=float)
            return np.asarray(state["emb_te"], dtype=float)
        return orig_transform(tfidf, svd, texts)

    core.fit_text_embedder = fit_text_embedder_patched
    core.transform_text_embedder = transform_text_embedder_patched


