def merge_excel(out_dir: str):
    """
    Merges strictly defined CSV files into a unified Excel workbook.
    - Accurately aligns Column Headers with Word manuscript conventions.
    - Merges split results for Table 4, 6, and 10 logically into single tables.
    - Excludes any intermediate tables (like "Anchor_*.csv") completely.
    """
    table_merge_dir = os.path.join(out_dir, "table_merge")
    ensure_dir(table_merge_dir)
    merged_path = os.path.join(table_merge_dir, "Paper_All_Tables_Merged.xlsx")

    core_csv_dir = os.path.join(out_dir, "table_out", "paper_tables_csv")
    anchor_out_dir = os.path.join(out_dir, "anchor_merge_outputs")

    with pd.ExcelWriter(merged_path, engine="openpyxl") as writer:

        def read_robust(path: str) -> Optional[pd.DataFrame]:
            if not path or not os.path.exists(path):
                return None
            if path.lower().endswith(".xlsx"):
                try:
                    return pd.read_excel(path)
                except:
                    return None
            for enc in ['utf-8', 'gbk', 'gb18030', 'utf-8-sig', 'latin1']:
                try:
                    return pd.read_csv(path, encoding=enc)
                except:
                    continue
            return None

        def add_sheet(path: str, sheet_name: str, formatter=None) -> bool:
            df = read_robust(path)
            if df is not None:
                if formatter:
                    df = formatter(df)
                df.to_excel(writer, sheet_name=sheet_name[:31], index=False)
                return True
            return False

        def find_file(directory: str, prefix: str, preferred_ext: str = ".csv") -> Optional[str]:
            if not os.path.exists(directory): return None
            matches = []
            for f in os.listdir(directory):
                if f.lower().startswith(prefix.lower()):
                    rest = f[len(prefix):]
                    if rest == "" or rest.startswith(".") or rest.startswith("_"):
                        matches.append(f)
            if not matches: return None
            for f in matches:
                if f.lower().endswith(preferred_ext): return os.path.join(directory, f)
            return os.path.join(directory, matches[0])

        # ---------------------------------------------------------
        # Main Tables 1 to 3
        # ---------------------------------------------------------
        add_sheet(find_file(core_csv_dir, "Table1"), "Table_1", format_table_1)
        add_sheet(find_file(core_csv_dir, "Table2"), "Table_2", format_table_2)
        add_sheet(find_file(core_csv_dir, "Table3"), "Table_3", format_table_3)

        # ---------------------------------------------------------
        # Table 4: Merge Shapley (Table4) + Drop-One (Table5)
        # ---------------------------------------------------------
        df_t4_s = read_robust(find_file(core_csv_dir, "Table4"))
        df_t4_d = read_robust(find_file(core_csv_dir, "Table5"))
        if df_t4_s is not None and df_t4_d is not None:
            if 'drop' in df_t4_d.columns:
                df_t4_d = df_t4_d.rename(columns={'drop': 'metric'})

            df_t4 = pd.merge(df_t4_s, df_t4_d, on='metric', how='outer')
            df_t4 = df_t4.rename(columns={
                'metric': 'Block',
                'result': 'Shapley Value',
                'R2_full': 'R2 Full',
                'R2_dropped': 'R2 Dropped',
                'delta_R2': 'Delta R2'
            })
            df_t4.to_excel(writer, sheet_name="Table_4", index=False)

        # ---------------------------------------------------------
        # Table 5: FE Ablation Tests (Core Table 6)
        # ---------------------------------------------------------
        add_sheet(find_file(core_csv_dir, "Table6"), "Table_5", format_table_5)

        # ---------------------------------------------------------
        # Table 6: Merge FE Shapley (Table7) + Drop-One (Table8)
        # ---------------------------------------------------------
        df_t6_s = read_robust(find_file(core_csv_dir, "Table7"))
        df_t6_d = read_robust(find_file(core_csv_dir, "Table8"))
        if df_t6_s is not None and df_t6_d is not None:
            if 'drop' in df_t6_d.columns:
                df_t6_d = df_t6_d.rename(columns={'drop': 'metric'})

            df_t6 = pd.merge(df_t6_s, df_t6_d, on='metric', how='outer')
            if 'cv_tag' in df_t6.columns: df_t6 = df_t6.drop(columns=['cv_tag'])
            df_t6 = df_t6.rename(columns={
                'metric': 'Fixed Effect',
                'result': 'Shapley Value',
                'R2_full': 'R2 Full',
                'R2_dropped': 'R2 Dropped',
                'delta_R2': 'Delta R2'
            })
            df_t6.to_excel(writer, sheet_name="Table_6", index=False)

        # ---------------------------------------------------------
        # Table 7: Mechanism proxy CV (Core Table 9)
        # ---------------------------------------------------------
        add_sheet(find_file(core_csv_dir, "Table9"), "Table_7", format_table_7)

        # ---------------------------------------------------------
        # Table 8: Heat Robustness (Core Table 10)
        # ---------------------------------------------------------
        add_sheet(find_file(core_csv_dir, "Table10"), "Table_8")

        # ---------------------------------------------------------
        # Table 9: Supplier Anchor
        # ---------------------------------------------------------
        fpath_t9 = find_file(anchor_out_dir, "table9_supplier_anchoring", preferred_ext=".csv")
        if not fpath_t9:
            alt_path = os.path.join(anchor_out_dir, "table9_supplier_anchoring_summary.csv")
            if os.path.exists(alt_path): fpath_t9 = alt_path
        add_sheet(fpath_t9, "Table_9")

        # ---------------------------------------------------------
        # Table 10: Validation Schemes (Core Table11 & AppendixTable5)
        # ---------------------------------------------------------
        df_t10_r = read_robust(find_file(core_csv_dir, "Table11"))
        df_t10_g = read_robust(find_file(core_csv_dir, "AppendixTable5"))
        if df_t10_r is not None and df_t10_g is not None:
            cols_to_keep = ['metric', 'mean', 'std']
            df1 = df_t10_r[cols_to_keep] if set(cols_to_keep).issubset(df_t10_r.columns) else df_t10_r
            df2 = df_t10_g[cols_to_keep] if set(cols_to_keep).issubset(df_t10_g.columns) else df_t10_g

            df_t10 = pd.merge(df1, df2, on='metric', suffixes=('_Random', '_Group'), how='outer')
            df_t10 = df_t10.rename(columns={
                'metric': 'Metric',
                'mean_Random': 'Random K-fold Mean',
                'std_Random': 'Random K-fold SD',
                'mean_Group': 'Group K-fold Mean',
                'std_Group': 'Group K-fold SD'
            })
            df_t10.to_excel(writer, sheet_name="Table_10", index=False)

        # ---------------------------------------------------------
        # Appendices Mapping (Strictly paper items)
        # ---------------------------------------------------------
        add_sheet(find_file(core_csv_dir, "AppendixTable1"), "App_Table_C1")
        add_sheet(find_file(core_csv_dir, "AppendixTable2"), "App_Table_C2")
        add_sheet(find_file(core_csv_dir, "AppendixTable3"), "App_Table_D1", format_app_d1)
        add_sheet(find_file(core_csv_dir, "AppendixTable4"), "App_Table_G1", format_app_g1)

        # NOTE: App_Table_A1 mapping removed entirely.

    print(f"\n[OK] All core tables successfully merged and correctly mapped to Paper layout into: {merged_path}")


